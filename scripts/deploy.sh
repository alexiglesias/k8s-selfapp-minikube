#!/usr/bin/env bash
# Deploys selfapp to Minikube, into the dev or prod namespace.
#
# Usage:
#   ./scripts/deploy.sh dev
#   ./scripts/deploy.sh prod
#
# - Images are built inside Minikube from ../docker-buildlab-selfapp
#   (dev -> tag "dev", prod -> pinned tag "v1").
# - Passwords live in charts/selfapp/<env>.secrets.yaml (git-ignored).
#   If that file doesn't exist yet, it's created with random passwords.
set -euo pipefail

ENV="${1:-}"
if [ "${ENV}" != "dev" ] && [ "${ENV}" != "prod" ]; then
  echo "Usage: $0 <dev|prod>" >&2
  exit 1
fi

cd "$(dirname "$0")/.."

NAMESPACE="selfapp-${ENV}"
CHART="./charts/selfapp"
SRC="../docker-buildlab-selfapp"
SECRETS="${CHART}/${ENV}.secrets.yaml"
if [ "${ENV}" = "dev" ]; then TAG="dev"; else TAG="v1"; fi

# --- Passwords -----------------------------------------------------------
if [ ! -f "${SECRETS}" ]; then
  echo "[INFO] Creating ${SECRETS} with random passwords..."
  cat > "${SECRETS}" <<EOF
# Generated by deploy.sh - git-ignored, never commit this file.
mysql:
  rootPassword: "$(openssl rand -hex 16)"
  password: "$(openssl rand -hex 16)"
rabbitmq:
  password: "$(openssl rand -hex 16)"
EOF
  chmod 600 "${SECRETS}"
fi

# Safety net: refuse to continue if git would track the passwords file
if ! git check-ignore -q "${SECRETS}"; then
  echo "[ERROR] ${SECRETS} is not git-ignored. Fix .gitignore first." >&2
  exit 1
fi

VALUES=(-f "${CHART}/values-${ENV}.yaml" -f "${SECRETS}")

# --- Lint first (fail fast, before the slow image build) ------------------
echo "[INFO] Linting the chart..."
helm lint "${CHART}" "${VALUES[@]}"

# --- Images --------------------------------------------------------------
if [ ! -d "${SRC}" ]; then
  echo "[ERROR] ${SRC} not found. Clone docker-buildlab-selfapp next to this repo." >&2
  exit 1
fi
echo "[INFO] Building images inside Minikube (tag: ${TAG})..."
minikube image build -t "selfapp-lite:${TAG}" "${SRC}/app"
minikube image build -t "selfapp-lite-web:${TAG}" "${SRC}/web"

# --- Deploy --------------------------------------------------------------
echo "[INFO] Deploying to namespace ${NAMESPACE}..."
helm upgrade --install selfapp "${CHART}" \
  -n "${NAMESPACE}" --create-namespace \
  "${VALUES[@]}" \
  --wait --timeout 8m

echo "[DONE]"
kubectl get pods -n "${NAMESPACE}"
